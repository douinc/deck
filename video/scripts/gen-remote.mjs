const across = SW + unit * 0.05 - margin - RO.w;
const up = across < readoutR ? Math.sqrt(readoutR * readoutR - across * across) : 0;
const readoutTop = Math.max(16, pivot.y - up - RO.h);
const timeSize = unit * 0.19, capSize = timeSize / phi ** 3;

